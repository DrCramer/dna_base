import { expect, test } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

test('экспертизы: реальные список, два RT-файла, мишени, snapshot и печать', async ({ page }) => {
  test.setTimeout(90_000)
  const suffix = Date.now()
  const custom = `АБ-${suffix}/1`
  const exam = `E2E-${suffix}`
  const name = `Экспертиза ${suffix}`
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Войти' }).click()
  await expect(page.getByText('ДНК реестр', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Протоколы', exact: true }).click()
  await page.getByRole('button', { name: 'Создать', exact: true }).click()
  await page.getByRole('tab', { name: 'Генетические экспертизы' }).click()
  const yearInput = page.getByLabel('Год экспертизы', { exact: true })
  await yearInput.fill('')
  await yearInput.pressSequentially('2025')
  await yearInput.press('Tab')
  await expect(yearInput).toHaveValue('2025')
  await yearInput.fill('2026')
  await yearInput.press('Tab')
  await expect(yearInput).toHaveValue('2026')
  await expect(page.getByPlaceholder('№ рег РЦСМЭ от')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Партии протокола' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Вставить список номеров', exact: true }).click()
  await page.getByLabel('Номера объектов экспертиз').fill(`251-1\n251-80\n${custom}`)
  await page.getByRole('button', { name: 'Проверить', exact: true }).click()
  await expect(page.getByLabel('Экспертиза объекта 3')).toBeVisible()
  await page.getByLabel('Экспертиза объекта 3').fill(exam)
  await page.getByRole('button', { name: 'Проверить', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить к текущему' }).click()
  await expect(page.locator('.genetic-selector-toolbar')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Предпросмотр печати', exact: true })).toBeEnabled()
  await expect(page.locator('.protocol-document-meta output')).toHaveText(/3 \/ /)
  await page.getByRole('button', { name: 'Импорт RT', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Импорт RT экспертиз' })
  await dialog.locator('input[type=file]').setInputFiles([
    { name: `one-${suffix}.csv`, mimeType: 'text/csv', buffer: Buffer.from(`Sample Name,Target Name,Quantity,Ct\n251-1,Long,0.5,27\n251-1,Small,0.7,26\n251-1,Y,0.02,29\n${custom},Small,0.3,25\n`) },
    { name: `two-${suffix}.csv`, mimeType: 'text/csv', buffer: Buffer.from(`Sample Name,Target Name,Quantity,Ct\nManual-${suffix},Long,1.2,27\nManual-${suffix},Small,0.8,26\nManual-${suffix},Y,0.1,29\n`) }
  ])
  await dialog.getByRole('button', { name: 'Проверить файлы' }).click()
  await expect(dialog.getByLabel(`Объект для Manual-${suffix}`)).toBeVisible()
  await dialog.getByLabel(`Объект для Manual-${suffix}`).selectOption({ label: '251-80 · 251-2026' })
  await dialog.getByRole('button', { name: 'Импортировать', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByText('Разведения', { exact: true }).click()
  await page.getByLabel('Все мишени', { exact: true }).check()
  await expect(page.getByLabel('Small для 251-1', { exact: true })).toBeChecked()
  const previewResponse = page.waitForResponse((response) => response.url().endsWith('/protocols/preview') && response.request().postDataJSON().dilution.target_overrides && Object.values(response.request().postDataJSON().dilution.target_overrides).includes('long'))
  await page.getByLabel('Long для 251-1', { exact: true }).click()
  const preview = await (await previewResponse).json()
  expect(preview.dilutions.find((row: { display_name: string }) => row.display_name === '251-1').source_concentration).toBe(0.5)
  expect(preview.dilutions.find((row: { display_name: string }) => row.display_name === '251-80').source_concentration).toBe(0.8)
  await expect(page.getByLabel('Small для 251-1', { exact: true })).not.toBeChecked()
  await page.getByLabel('Округление объема H₂O').check()
  await page.getByLabel('Минимальный объём 15 мкл').check()
  await page.locator('.protocol-name-field input').fill(name)
  const savedResponse = page.waitForResponse((response) => /\/api\/protocols$/.test(response.url()) && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Сохранить черновик' }).click()
  const saved = await (await savedResponse).json()
  expect(saved.kind).toBe('genetic_examination')
  expect(saved.snapshot.objects).toHaveLength(3)
  expect(saved.snapshot.objects.every((obj: Record<string, unknown>) => !('party_id' in obj))).toBe(true)
  await page.getByRole('button', { name: 'Сохранён', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Редактировать протокол' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('tab', { name: 'Генетические экспертизы' })).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('.protocol-name-field input')).toHaveValue(name)
  await expect(page.locator('.protocol-document-meta input[type=number]')).toHaveValue(String(saved.protocol_no))
  await page.getByRole('button', { name: 'Предпросмотр печати', exact: true }).click()
  const printing = page.getByRole('dialog', { name: 'Что печатать' })
  await printing.getByLabel('Выделение', { exact: true }).uncheck()
  await printing.getByLabel('RT', { exact: true }).uncheck()
  await printing.getByLabel('Разведения', { exact: true }).check()
  await printing.getByRole('button', { name: 'Предпросмотр', exact: true }).click()
  await expect(page.locator('.protocol-preview-modal')).toBeVisible()
  await expect(page.locator('.protocol-print-root')).toContainText(custom)
  await expect(page.locator('.protocol-print-root')).not.toContainText('Округление разведений')
  await expect(page.locator('.protocol-print-root input')).toHaveCount(0)
  await mkdir('/tmp/dna-genetic-e2e', { recursive: true })
  await page.screenshot({ path: '/tmp/dna-genetic-e2e/desktop.png', fullPage: true })
  await page.emulateMedia({ media: 'print' })
  await page.evaluate(() => document.body.classList.add('protocol-printing'))
  await page.pdf({ path: '/tmp/dna-genetic-e2e/protocol.pdf', printBackground: true, preferCSSPageSize: true })
  await page.emulateMedia({ media: 'screen' })
  await page.evaluate(() => document.body.classList.remove('protocol-printing'))
  await page.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '/tmp/dna-genetic-e2e/mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.getByRole('button', { name: 'Редактировать протокол', exact: true }).click()
  await expect(page.getByRole('heading', { name: `${name} · версия 2`, exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Назад', exact: true }).click()
  await expect(page.getByRole('tab', { name: 'Генетические экспертизы' })).toHaveAttribute('aria-selected', 'true')
  await page.getByPlaceholder('№, название, экспертиза, объект, набор...').fill(name)
  await expect(page.getByRole('button', { name, exact: true })).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'Партии', exact: true })).toHaveCount(0)
  await page.getByLabel('Год экспертизы', { exact: true }).fill('2025')
  await page.getByLabel('Год экспертизы', { exact: true }).press('Tab')
  await expect(page.getByRole('button', { name, exact: true })).toHaveCount(0)
  await page.getByLabel('Год экспертизы', { exact: true }).fill('2026')
  await page.getByLabel('Год экспертизы', { exact: true }).press('Tab')
  await expect(page.getByRole('button', { name, exact: true })).toBeVisible()
  const savedRow = page.getByRole('row').filter({ has: page.getByRole('button', { name, exact: true }) })
  page.once('dialog', (confirm) => confirm.accept())
  await savedRow.getByTitle('Архивировать', { exact: true }).click()
  await expect(page.getByRole('button', { name, exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Архив', exact: true }).click()
  await expect(page.getByRole('button', { name, exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

test('экспертизы: импорт Excel сохраняет отдельные раскладки PCR и источника', async ({ page }) => {
  test.skip(!process.env.GENETIC_E2E_EXCEL, 'Укажите подготовленный GENETIC_E2E_EXCEL')
  await page.goto('/')
  await page.getByRole('button', { name: 'Войти' }).click()
  await expect(page.getByText('ДНК реестр', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Протоколы', exact: true }).click()
  await page.getByRole('button', { name: 'Создать', exact: true }).click()
  await page.getByRole('tab', { name: 'Генетические экспертизы' }).click()
  await page.locator('.genetic-selector-toolbar input[type=file]').setInputFiles(process.env.GENETIC_E2E_EXCEL!)
  const dialog = page.getByRole('dialog', { name: 'Импорт Excel экспертиз' })
  await expect(dialog).toBeVisible()
  await dialog.getByLabel('Экспертиза объекта 1').fill('ExcelE2E')
  await dialog.getByLabel('Экспертиза объекта 2').fill('ExcelE2E')
  await dialog.getByRole('button', { name: 'Проверить', exact: true }).click()
  await dialog.getByText('Лунки и параметры Excel', { exact: true }).click()
  await dialog.getByLabel('Плашка Excel').selectOption('pcr:1')
  await expect(dialog.getByLabel('Объект в PCR 1 H12')).toBeVisible()
  const responsePromise = page.waitForResponse((response) => response.url().endsWith('/protocols/preview') && response.request().postDataJSON().imported_wells?.length > 0)
  await dialog.getByRole('button', { name: 'Заменить текущий список' }).click()
  const preview = await (await responsePromise).json()
  expect(preview.layouts.pcr.plates[0].wells.find((well: { display_name: string }) => well.display_name === 'ExcelEX-1').well).toBe('H12')
  expect(preview.layouts.source.plates[0].wells.find((well: { display_name: string }) => well.display_name === 'ExcelEX-1').well).toBe('A1')
  await expect(page.locator('.protocol-performer-chips')).toContainText(['Неизвестный исполнитель', '', '', ''])
  page.once('dialog', (confirm) => confirm.dismiss())
  await page.getByLabel('Аллельные лестницы', { exact: true }).click()
  await expect(page.getByLabel('Аллельные лестницы', { exact: true })).not.toBeChecked()
})
